"""layout-plan.toml: the editable list of moves `apply-plan` performs, and its markdown summary.

    version = 1
    unassigned = ["pkg/odd.py"]          # files the heuristic could not group (informational)
    split_by_hand = ["pkg/utils.py"]     # catch-all modules: split by responsibility by hand

    [[group]]                            # optional; one per group, for the commit message
    name = "user"
    message = "layout: move the user modules into pkg/user"

    [[new_package]]                      # optional; docstring of an __init__.py apply-plan creates
    path = "pkg/user"
    docstring = "User accounts: the model, its service and its HTTP routes."

    [[move]]                             # one per module; `group` ties moves into one commit
    group = "user"
    from = "pkg/user_model.py"
    to = "pkg/user/model.py"
"""
from __future__ import annotations

import json
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

PLAN_NAME = "layout-plan.toml"
SUMMARY_NAME = "layout-refactor-plan.md"


class PlanError(ValueError):
    """layout-plan.toml is unreadable or invalid."""


@dataclass(frozen=True)
class Move:
    group: str
    src: str        # project-relative, `/`-separated
    dst: str


@dataclass
class Plan:
    moves: list[Move] = field(default_factory=list)
    packages: dict[str, str] = field(default_factory=dict)   # new package path -> docstring
    messages: dict[str, str] = field(default_factory=dict)   # group -> commit message
    unassigned: list[str] = field(default_factory=list)
    split_by_hand: list[str] = field(default_factory=list)

    def groups(self) -> list[str]:
        return list(dict.fromkeys(m.group for m in self.moves))

    def moves_of(self, group: str) -> list[Move]:
        return [m for m in self.moves if m.group == group]

    def message(self, group: str) -> str:
        moves = self.moves_of(group)
        dirs = sorted({m.dst.rsplit("/", 1)[0] for m in moves})
        return self.messages.get(group) or f"layout: move {len(moves)} module(s) into {', '.join(dirs)} ({group})"


def _q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def _norm(p: str) -> str:
    return p.replace("\\", "/").strip("/")


def render(plan: Plan) -> str:
    lines = ["# layout-plan.toml: the moves `layout-guard apply-plan` performs, one commit per group.",
             "# Generated by `layout-guard plan` from file names only. EDIT IT before applying: regroup",
             "# modules by real responsibility, rename targets, write the package docstrings.",
             "version = 1",
             f"unassigned = [{', '.join(map(_q, plan.unassigned))}]  # no obvious group: decide by hand",
             f"split_by_hand = [{', '.join(map(_q, plan.split_by_hand))}]  # catch-all modules"]
    for g in plan.groups():
        moves = plan.moves_of(g)
        lines += ["", "[[group]]", f"name = {_q(g)}", f"message = {_q(plan.message(g))}"]
        for path in sorted({m.dst.rsplit('/', 1)[0] for m in moves}):
            if path in plan.packages:
                lines += ["", "[[new_package]]", f"path = {_q(path)}", f"docstring = {_q(plan.packages[path])}"]
        for m in moves:
            lines += ["", "[[move]]", f"group = {_q(g)}", f"from = {_q(m.src)}", f"to = {_q(m.dst)}"]
    return "\n".join(lines) + "\n"


def _keys(table, allowed: set[str], where: str) -> None:
    if not isinstance(table, dict):
        raise PlanError(f"{where} must be a table")
    extra = sorted(set(table) - allowed)
    if extra:
        raise PlanError(f"unknown key(s) in {where}: {extra}; allowed: {sorted(allowed)}")


def _str(table: dict, key: str, where: str) -> str:
    value = table.get(key)
    if not isinstance(value, str) or not value.strip():
        raise PlanError(f'{where} needs {key} = "..."')
    return value


def parse(data: dict) -> Plan:
    _keys(data, {"version", "unassigned", "split_by_hand", "group", "new_package", "move"}, PLAN_NAME)
    if data.get("version", 1) != 1:
        raise PlanError("version must be 1")
    plan = Plan(unassigned=list(data.get("unassigned", [])), split_by_hand=list(data.get("split_by_hand", [])))
    for i, g in enumerate(data.get("group", [])):
        _keys(g, {"name", "message"}, f"[[group]] #{i + 1}")
        plan.messages[_str(g, "name", f"[[group]] #{i + 1}")] = g.get("message", "")
    for i, p in enumerate(data.get("new_package", [])):
        where = f"[[new_package]] #{i + 1}"
        _keys(p, {"path", "docstring"}, where)
        plan.packages[_norm(_str(p, "path", where))] = p.get("docstring", "")
    for i, m in enumerate(data.get("move", [])):
        where = f"[[move]] #{i + 1}"
        _keys(m, {"group", "from", "to"}, where)
        src, dst = _norm(_str(m, "from", where)), _norm(_str(m, "to", where))
        if not (src.endswith(".py") and dst.endswith(".py")):
            raise PlanError(f"{where}: from and to must be .py files ({src} -> {dst})")
        plan.moves.append(Move(_str(m, "group", where), src, dst))
    unknown = sorted(set(plan.messages) - set(plan.groups()))
    if unknown:
        raise PlanError(f"[[group]] name(s) without any [[move]]: {unknown}")
    return plan


def load(path: Path) -> Plan:
    try:
        return parse(tomllib.loads(path.read_text(encoding="utf-8-sig")))
    except tomllib.TOMLDecodeError as exc:
        raise PlanError(f"{path}: not valid TOML: {exc}") from exc
    except OSError as exc:
        raise PlanError(f"{path}: cannot read: {exc}") from exc


def summary(plan: Plan) -> str:
    """The human-readable layout-refactor-plan.md (generated; edit layout-plan.toml instead)."""
    lines = ["# Layout refactor plan", "",
             f"Generated from `{PLAN_NAME}`, which is what `layout-guard apply-plan` applies. Edit that",
             "file, not this one, then run `layout-guard plan` again to refresh this summary.", "",
             "Apply on a branch (never main/master), one tested commit per group:", "",
             "```sh", "git switch -c layout-cleanup", "layout-guard apply-plan --all --dry-run",
             "layout-guard apply-plan --all", "```", ""]
    for g in plan.groups():
        lines += [f"## Group `{g}`", "", f"Commit: {plan.message(g)}", "", "| From | To |", "|---|---|"]
        lines += [f"| `{m.src}` | `{m.dst}` |" for m in plan.moves_of(g)]
        for path in sorted({m.dst.rsplit('/', 1)[0] for m in plan.moves_of(g)} & set(plan.packages)):
            lines += ["", f"New package `{path}/`: {plan.packages[path]}"]
        lines.append("")
    if plan.split_by_hand:
        lines += ["## Catch-all modules (split by responsibility by hand)", "",
                  *(f"- `{f}`" for f in plan.split_by_hand), ""]
    if plan.unassigned:
        lines += ["## No obvious group (read them, decide, add [[move]] entries)", "",
                  *(f"- `{f}`" for f in plan.unassigned), ""]
    if not plan.moves:
        lines += ["Nothing to move.", ""]
    return "\n".join(lines)
